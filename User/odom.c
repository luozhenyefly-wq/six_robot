#include "odom.h"

/* ================= 里程计 ================= */
/*
当需要通过上位机进行slam或者导航的话，会需要用到里程计计数
如果不需要进行导航开发，暂无其他用处
*/

volatile float odom_ds = 0.0f;      /* 带符号：前进为正、后退为负。
                                       注意这不是"路程" —— 后退时它变负，
                                       上位机要靠它的符号算 dx/dy 的方向。*/


/* ---------------------------------------------------------------------------
 * 累加：步态任务每拍调用一次
 *
 * 为什么用临界区：
 *   odom_ds += ds 编译出来是"读 -> 加 -> 写回"三条指令。
 *   如果发送任务在中间把它清零，写回时会把那个已经过期的旧值又写回去，
 *   那份位移就被重复计算了。临界区把这三条指令变成不可分割的整体。
 * -------------------------------------------------------------------------*/
void Odom_Add(float ds)
{
    uint32_t pm = __get_PRIMASK();
    __disable_irq();

    odom_ds += ds;

    __set_PRIMASK(pm);
}


/* ---------------------------------------------------------------------------
 * 取走并清零：发送任务每帧调用一次
 *
 * 关键：读和清零必须在同一个临界区里，中间不能夹任何东西。
 *
 *   错误写法（会稳定丢数据）：
 *       ds = odom_ds;               // 读
 *       sprintf(...); HAL_UART_Transmit(...);   // 发送，阻塞约 2ms
 *       odom_ds = 0.0f;             // 清零  <- 这 2ms 里累加的位移被吞掉
 *
 *   正确用法：
 *       ds = Odom_Take();           // 先原子取走，几微秒
 *       sprintf / HAL_UART_Transmit // 再慢慢发，发多久都不影响
 * -------------------------------------------------------------------------*/
float Odom_Take(void)
{
    float d;
    uint32_t pm = __get_PRIMASK();
    __disable_irq();

    d       = odom_ds;
    odom_ds = 0.0f;

    __set_PRIMASK(pm);

    return d;
}


void Odom_Reset(void)
{
    uint32_t pm = __get_PRIMASK();
    __disable_irq();

    odom_ds = 0.0f;

    __set_PRIMASK(pm);
}
